from __future__ import annotations

import math
import os
import shutil
import subprocess
import sys
import time
from dataclasses import replace
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
import psutil
from filelock import FileLock

from mlforge.artifacts import artifact_path, load_pipeline
from mlforge.config import Settings
from mlforge.datasets import inspect_csv, sample_csv
from mlforge.drift import compare
from mlforge.errors import ForgeError
from mlforge.models import feature_frame
from mlforge.schemas import ExperimentConfig, PredictionResponse
from mlforge.splitting import build_split
from mlforge.storage import Store, identifier, now, uid
from mlforge.training import validate_problem


class Forge:
    def __init__(self, settings: Settings | None = None):
        self.settings = settings or Settings.default()
        self.settings = replace(self.settings, home=self.settings.home.resolve())
        self.settings.prepare()
        self.store = Store(self.settings.home)
        self.store.retain_logs(self.settings.max_logs, self.settings.retention_days)

    def logs(self, limit: int = 100) -> list[dict]:
        self.store.retain_logs(self.settings.max_logs, self.settings.retention_days)
        return self.store.list("prediction", limit)

    def ingest(self, raw: bytes, name: str, source: str = "upload") -> dict:
        data = inspect_csv(raw, self.settings)
        with FileLock(str(self.settings.home / "datasets.lock"), timeout=10):
            for record in self.store.list("dataset", 1000):
                if record["fingerprint"] == data.fingerprint:
                    return record
            if (
                self.settings.max_datasets
                and self.store.overview()["datasets"] >= self.settings.max_datasets
            ):
                raise ForgeError(
                    "This temporary demo workspace has reached its dataset limit. Delete a dataset or use local mode.",
                    "demo_limit",
                    409,
                )
            record = {
                "id": uid(),
                "name": Path(name.replace("\\", "/")).name[:100] or "dataset.csv",
                "fingerprint": data.fingerprint,
                "rows": len(data.frame),
                "columns": len(data.schema),
                "schema": data.schema,
                "profile": data.profile,
                "source": source,
                "created_at": now(),
                "stored_bytes": len(data.canonical),
            }
            (self.settings.home / "datasets" / f"{record['id']}.csv").write_bytes(data.canonical)
            return self.store.save("dataset", record)

    def sample(self, task: str) -> dict:
        return self.ingest(
            sample_csv(task),
            f"synthetic-{task}.csv",
            "synthetic; seed=42; generated by scikit-learn",
        )

    def data(self, key: str):
        record = self.store.get("dataset", key)
        path = self.settings.home / "datasets" / f"{identifier(key)}.csv"
        if not path.exists():
            raise ForgeError("Stored dataset is missing; upload it again", "dataset_missing", 409)
        data = inspect_csv(path.read_bytes(), self.settings)
        if data.fingerprint != record["fingerprint"]:
            raise ForgeError("Stored dataset integrity check failed", "dataset_integrity", 409)
        return data

    def delete_dataset(self, key: str) -> None:
        self.store.get("dataset", key)
        for exp in self.store.list("experiment", 1000):
            if exp["config"]["dataset_id"] == key and exp["status"] in ("queued", "running"):
                raise ForgeError(
                    "Cannot delete a dataset used by an active experiment", "busy", 409
                )
        (self.settings.home / "datasets" / f"{identifier(key)}.csv").unlink(missing_ok=True)
        self.store.remove("dataset", key)

    def preflight(self, config: ExperimentConfig) -> dict:
        if len(config.features) > self.settings.max_features:
            raise ForgeError(f"Select at most {self.settings.max_features} features")
        data = self.data(config.dataset_id)
        y, notes = validate_problem(data, config)
        split = build_split(data.frame, y, config)
        return {
            "warnings": notes + split.warnings,
            "rows": {
                "train": len(split.train),
                "validation": len(split.validation),
                "test": len(split.test),
                "purged": len(split.purged),
            },
            "effective_cv_folds": len(split.folds),
            "dataset_fingerprint": data.fingerprint,
        }

    def start(self, config: ExperimentConfig, background: bool = True) -> dict:
        if (
            self.settings.max_experiments
            and self.store.overview()["experiments"] >= self.settings.max_experiments
        ):
            raise ForgeError(
                "This temporary demo workspace has reached its experiment limit. Use local mode for further experiments.",
                "demo_limit",
                409,
            )
        check = self.preflight(config)
        self.recover_jobs()
        record = {
            "id": uid(),
            "name": config.name,
            "created_at": now(),
            "status": "queued",
            "config": config.model_dump(),
            "dataset_fingerprint": check["dataset_fingerprint"],
            "warnings": check["warnings"],
            "candidates": [],
            "progress": "Queued",
            "cancel_requested": False,
            "pid": None,
        }
        self.store.reserve_experiment(record)
        if not background:
            from mlforge.worker import execute

            execute(self.settings, record["id"])
            return self.store.get("experiment", record["id"])
        env = dict(
            os.environ,
            MLFORGE_HOME=str(self.settings.home),
            OMP_NUM_THREADS="1",
            OPENBLAS_NUM_THREADS="1",
            MKL_NUM_THREADS="1",
            NUMEXPR_NUM_THREADS="1",
        )
        log = self.settings.home / "experiments" / f"{record['id']}.log"
        try:
            with log.open("w", encoding="utf-8") as output:
                subprocess.Popen(
                    [
                        sys.executable,
                        "-m",
                        "mlforge.worker",
                        "--home",
                        str(self.settings.home),
                        "--id",
                        record["id"],
                    ],
                    stdout=output,
                    stderr=subprocess.STDOUT,
                    cwd=Path(__file__).resolve().parents[1],
                    env=env,
                    creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0,
                )
        except OSError as exc:
            self.store.patch(
                "experiment", record["id"], status="failed", error="Worker could not be started"
            )
            raise ForgeError("Worker could not be started", "worker_failed", 500) from exc
        return record

    def recover_jobs(self) -> None:
        for exp in self.store.list("experiment", 1000):
            if exp["status"] not in ("queued", "running"):
                continue
            age = (
                datetime.now(timezone.utc) - datetime.fromisoformat(exp["created_at"])
            ).total_seconds()
            if exp.get("pid"):
                try:
                    process = psutil.Process(exp["pid"])
                    alive = (
                        process.is_running()
                        and abs(process.create_time() - exp.get("process_created", 0)) < 1
                    )
                except psutil.Error:
                    alive = False
                if not alive:
                    self.store.patch(
                        "experiment",
                        exp["id"],
                        status="failed",
                        error="Training worker was interrupted; start a new experiment to retry",
                    )
            elif age > 60:
                self.store.patch(
                    "experiment", exp["id"], status="failed", error="Queued worker never started"
                )

    def cancel(self, key: str) -> None:
        exp = self.store.get("experiment", key)
        if exp["status"] not in ("queued", "running"):
            raise ForgeError("Only active experiments can be cancelled", "conflict", 409)
        self.store.patch("experiment", key, cancel_requested=True)
        if exp.get("pid") and exp["pid"] != os.getpid():
            try:
                process = psutil.Process(exp["pid"])
                if (
                    abs(process.create_time() - exp.get("process_created", 0)) < 1
                    and "mlforge.worker" in process.cmdline()
                    and key in process.cmdline()
                ):
                    process.terminate()
                    process.wait(5)
            except psutil.Error:
                pass
        current = self.store.get("experiment", key)
        if current["status"] in ("queued", "running"):
            self.store.patch("experiment", key, status="cancelled", progress="Cancelled by user")

    def register(self, experiment_id: str, name: str) -> dict:
        if self.settings.max_models and self.store.overview()["models"] >= self.settings.max_models:
            raise ForgeError(
                "This temporary demo workspace has reached its model limit. Delete a registry copy or use local mode.",
                "demo_limit",
                409,
            )
        name = name.strip()
        if not name or len(name) > 100:
            raise ForgeError("Choose a model name between 1 and 100 characters")
        exp = self.store.get("experiment", experiment_id)
        if exp["status"] != "succeeded":
            raise ForgeError("Only successful experiments can be registered", "conflict", 409)
        with FileLock(str(self.settings.home / "registry.lock"), timeout=10):
            model = {
                "id": uid(),
                "name": name,
                "version": self.store.highest_model_version(name) + 1,
                "experiment_id": experiment_id,
                "created_at": now(),
                "status": "registered",
                "task": exp["config"]["task"],
                "target": exp["config"]["target"],
                "feature_schema": exp["result"]["feature_schema"],
                "features": exp["config"]["features"],
                "dataset_fingerprint": exp["dataset_fingerprint"],
                "primary_metric": exp["config"]["primary_metric"],
                "validation": exp["result"]["candidates"][exp["result"]["selected_index"]][
                    "validation"
                ],
                "final_test": exp["result"]["final_test"],
                "preprocessing": {
                    "numeric_imputation": exp["config"]["numeric_imputation"],
                    "categorical_imputation": exp["config"]["categorical_imputation"],
                    "encoded_features": exp["result"]["preprocessing_features"],
                },
                "reference": exp["result"]["reference"],
                **exp["artifact"],
            }
            source = artifact_path(self.settings.home, "experiments", experiment_id)
            # Validate the application's own source before creating a new registry copy.
            load_pipeline(source, model)
            target = artifact_path(self.settings.home, "models", model["id"])
            model["artifact_path"] = target.relative_to(self.settings.home).as_posix()
            target.parent.mkdir(parents=True, exist_ok=False)
            shutil.copyfile(source, target)
            return self.store.save("model", model)

    def delete_model(self, key: str) -> None:
        self.store.get("model", key)
        path = artifact_path(self.settings.home, "models", key)
        path.unlink(missing_ok=True)
        self.store.patch("model", key, status="deleted")

    def _prediction_frame(self, model: dict, rows: list[dict]) -> pd.DataFrame:
        if not rows or len(rows) > self.settings.max_predict_rows:
            raise ForgeError(f"Provide 1–{self.settings.max_predict_rows} prediction rows")
        expected = set(model["features"])
        specs = {s["name"]: s for s in model["feature_schema"]}
        for i, row in enumerate(rows):
            if not isinstance(row, dict) or set(row) != expected:
                raise ForgeError(f"Row {i}: provide exactly the registered feature fields")
            for name, value in row.items():
                if value is None:
                    continue  # Explicit null is imputed; omitted fields are rejected.
                kind = specs[name]["type"]
                if kind == "number" and (
                    isinstance(value, bool)
                    or not isinstance(value, (float, int))
                    or not math.isfinite(value)
                    or abs(value) > 1e12
                ):
                    raise ForgeError(f"Row {i}: {name} needs a finite numeric value or null")
                if kind == "boolean" and not isinstance(value, bool):
                    raise ForgeError(f"Row {i}: {name} needs a boolean or null")
                if kind == "string" and (
                    not isinstance(value, str) or len(value) > self.settings.max_cell_chars
                ):
                    raise ForgeError(f"Row {i}: {name} needs a bounded string or null")
        return feature_frame(
            pd.DataFrame(rows, columns=model["features"]),
            model["feature_schema"],
            model["features"],
        )

    def predict(
        self, model_id: str, rows: list[dict], demonstration: bool = False
    ) -> PredictionResponse:
        t0 = time.perf_counter()
        log = {
            "id": uid(),
            "created_at": now(),
            "model_id": model_id,
            "rows": len(rows),
            "status": "failed",
            "synthetic_demo": demonstration,
        }
        try:
            model = self.store.get("model", model_id)
            if model["status"] != "registered":
                raise ForgeError("Model artifact has been deleted", "artifact_missing", 409)
            log["version"] = model["version"]
            frame = self._prediction_frame(model, rows)
            pipeline = load_pipeline(artifact_path(self.settings.home, "models", model_id), model)
            prediction = pipeline.predict(frame)
            probabilities, classes = None, None
            if model["task"] == "classification" and hasattr(pipeline, "predict_proba"):
                probabilities = pipeline.predict_proba(frame).tolist()
                classes = [str(c) for c in pipeline.classes_]
            drift = compare(frame, model["reference"])
            duration = (time.perf_counter() - t0) * 1000
            log.update(status="succeeded", drift=drift)
            if model["task"] == "classification":
                values, counts = np.unique(prediction, return_counts=True)
                log["prediction_summary"] = {
                    str(k): int(v) for k, v in zip(values, counts, strict=False)
                }
            else:
                log["prediction_summary"] = {
                    "mean": float(np.mean(prediction)),
                    "std": float(np.std(prediction)),
                }
            return PredictionResponse(
                model_id=model_id,
                model_version=model["version"],
                task=model["task"],
                predictions=prediction.tolist(),
                probabilities=probabilities,
                classes=classes,
                duration_ms=duration,
                drift=drift,
            )
        except ForgeError as exc:
            log["error"] = str(exc)
            raise
        except Exception as exc:
            log["error"] = "Prediction computation failed"
            raise ForgeError(
                "Prediction failed; inspect feature types and artifact compatibility",
                "prediction_failed",
                500,
            ) from exc
        finally:
            log["duration_ms"] = (time.perf_counter() - t0) * 1000
            self.store.save("prediction", log)
            self.store.retain_logs(self.settings.max_logs, self.settings.retention_days)

    def drift_demo(self, key: str) -> dict:
        model = self.store.get("model", key)
        rows = []
        for i in range(100):
            row = {}
            for spec in model["feature_schema"]:
                baseline = model["reference"][spec["name"]]
                if spec["type"] == "number":
                    row[spec["name"]] = (
                        (baseline["mean"] or 0) + 8 * (baseline["std"] or 1) + i / 100
                    )
                elif spec["type"] == "boolean":
                    row[spec["name"]] = True
                else:
                    row[spec["name"]] = "__synthetic_shift__"
            rows.append(row)
        result = self.predict(key, rows, demonstration=True).model_dump()
        result["demonstration"] = (
            "Deterministic artificial input shift; not production performance evidence"
        )
        return result
